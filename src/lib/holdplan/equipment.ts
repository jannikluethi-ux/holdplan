import type { EquipmentDef, EquipmentRegion, PositionSlot, RoomFamily } from "./types.ts";

const IN = 25.4;
const LB = 0.45359237;
const inch = (n: number) => Math.round(n * IN);
const ftIn = (ft: number, inches = 0) => Math.round((ft * 12 + inches) * IN);
const lb = (n: number) => Math.round(n * LB);

function aircraftSlots(
  count: number,
  palletLength: number,
  palletWidth: number,
  innerLength: number,
  maxKg: number,
): PositionSlot[] {
  const start = -innerLength / 2 + palletLength / 2;
  const slots: PositionSlot[] = [];
  for (let i = 0; i < count; i++) {
    const x = start + i * palletLength;
    if (x + palletLength / 2 > innerLength / 2 + 10) break;
    slots.push({
      id: `pos-${String(i + 1).padStart(2, "0")}`,
      name: `MD ${i + 1}`,
      xMm: x,
      zMm: 0,
      lengthMm: palletLength,
      widthMm: palletWidth,
      maxKg,
    });
  }
  return slots;
}

function lashRing(length: number, width: number, step: number): { xMm: number; zMm: number }[] {
  const pts: { xMm: number; zMm: number }[] = [];
  const x0 = -length / 2 + 200;
  const x1 = length / 2 - 200;
  const z0 = -width / 2 + 80;
  const z1 = width / 2 - 80;
  for (let x = x0; x <= x1; x += step) {
    pts.push({ xMm: x, zMm: z0 }, { xMm: x, zMm: z1 });
  }
  return pts;
}

function euAxles(innerL: number, kingpinKg: number, bogieKg: number, bogieCount: number) {
  return [
    { id: "kingpin", name: "Kingpin / tractor", xMm: -innerL / 2 + 800, axleCount: 2, maxKg: kingpinKg },
    { id: "bogie", name: bogieCount >= 3 ? "Trailer tridem" : "Trailer tandem", xMm: innerL / 2 - 3400, axleCount: bogieCount, maxKg: bogieKg },
  ];
}

function usVanAxles(innerL: number) {
  return [
    { id: "kingpin", name: "Kingpin / drive", xMm: -innerL / 2 + inch(36), axleCount: 2, maxKg: lb(34000) },
    { id: "trailer", name: "Trailer tandem", xMm: innerL / 2 - inch(60), axleCount: 2, maxKg: lb(34000) },
  ];
}

